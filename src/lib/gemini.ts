export async function generateStory(
  options: StoryOptions
): Promise<StoryResult> {
  try {
    // Симулиране на забавяне за по-реалистично усещане
    await new Promise((resolve) => setTimeout(resolve, 2000));

    // Избор на подходящ темплейт според възрастовата група
    const template =
      storyTemplates[options.ageRange as keyof typeof storyTemplates] ||
      storyTemplates['5-7'];

    // Персонализиране на историята според промпта (опростена симулация)
    const customizedStory = template.replace(
      'малко зайче',
      options.prompt.includes('динозавър')
        ? 'малко динозавърче'
        : options.prompt.includes('робот')
        ? 'малък робот'
        : options.prompt.includes('принцеса')
        ? 'малка принцеса'
        : 'малко зайче'
    );

    return {
      text: customizedStory,
    };
  } catch (error) {
    console.error('Error generating story:', error);
    return {
      text: '',
      error:
        'Възникна грешка при генерирането на историята. Моля, опитайте отново.',
    };
  }
}

export async function generateBookTitle(
  prompt: string,
  ageRange: string
): Promise<string> {
  // Симулиране на забавяне
  await new Promise((resolve) => setTimeout(resolve, 500));

  // Базови заглавия според възрастовата група
  let baseTitle = '';
  if (ageRange === '2-4') {
    baseTitle = 'Малкото';
  } else if (ageRange === '5-7') {
    baseTitle = 'Невероятното';
  } else {
    baseTitle = 'Фантастичното';
  }

  // Извличаме ключова дума от подсказката
  const keywords = prompt.split(' ');
  const keyword = keywords.length > 3 ? keywords[3] : keywords[0];

  // Няколко примерни заглавия
  const titles = [
    `${baseTitle} Пътешествие на ${keyword}`,
    `Приключение в Космоса с ${keyword}`,
    `Тайната на ${keyword}`,
    `Приятели Завинаги: ${keyword}`,
    `Една Специална Нощ и ${keyword}`,
    `Малкият Герой и ${keyword}`,
  ];

  // Избираме случайно заглавие
  return titles[Math.floor(Math.random() * titles.length)];
}
